# scripts/download_dataset_c.py
"""
Downloads the 140k Real and Fake Faces dataset from Kaggle, resizes every
image to 224×224 (RGB, center-crop), and saves it to Google Drive under
datasets/dataset_c/ in the standard ImageFolder structure.

The dataset already contains train/valid/test splits and real/fake subfolders,
so no splitting is required. The script maps the source folder names to our
standard naming convention:
    fake  →  ai
    real  →  real
    valid →  val

Run once. Re-running is safe — already-saved images are skipped automatically.

Dataset source: https://www.kaggle.com/datasets/xhlulu/140k-real-and-fake-faces
Real images:    70k faces from Flickr-Faces-HQ (NVIDIA)
Fake images:    70k faces generated by StyleGAN
"""

import os
import time
from pathlib import Path

import kagglehub
from google.colab import drive
from PIL import Image, UnidentifiedImageError
from tqdm import tqdm

# ── CONFIG ────────────────────────────────────────────────────────────────────

DRIVE_ROOT   = "/content/drive/MyDrive/licenta"
DATASET_DIR  = os.path.join(DRIVE_ROOT, "datasets", "dataset_c")

IMG_SIZE    = (224, 224)
MAX_RETRIES = 3

# Mapping from Kaggle split folder names to our standard names
SPLIT_MAP = {
    "train": "train",
    "valid": "val",
    "test":  "test",
}

# Mapping from Kaggle label folder names to our standard names
LABEL_MAP = {
    "fake": "ai",
    "real": "real",
}

# ── HELPERS ───────────────────────────────────────────────────────────────────

def _mount_drive() -> None:
    if not os.path.isdir("/content/drive/MyDrive"):
        print("Mounting Google Drive …")
        drive.mount("/content/drive")
    else:
        print("Google Drive already mounted.")


def _make_dirs() -> None:
    for split in SPLIT_MAP.values():
        for label in LABEL_MAP.values():
            os.makedirs(os.path.join(DATASET_DIR, split, label), exist_ok=True)


def _preprocess(img: Image.Image) -> Image.Image:
    """RGB → scale shortest side to 224 → center-crop 224×224."""
    img   = img.convert("RGB")
    w, h  = img.size
    scale = IMG_SIZE[0] / min(w, h)
    nw    = max(IMG_SIZE[0], int(round(w * scale)))
    nh    = max(IMG_SIZE[1], int(round(h * scale)))
    img   = img.resize((nw, nh), Image.LANCZOS)
    left  = (nw - IMG_SIZE[0]) // 2
    upper = (nh - IMG_SIZE[1]) // 2
    return img.crop((left, upper, left + IMG_SIZE[0], upper + IMG_SIZE[1]))


def _save_with_retry(img: Image.Image, path: str) -> bool:
    for attempt in range(1, MAX_RETRIES + 1):
        try:
            img.save(path, format="PNG", optimize=False)
            return True
        except OSError as exc:
            print(f"    Save attempt {attempt}/{MAX_RETRIES} failed: {exc}")
            time.sleep(1.0 * attempt)
    return False


def _find_split_root(cache_path: str) -> str:
    """
    Walk the kagglehub cache to find the directory that contains
    train/, valid/ and test/ subfolders.
    """
    for dirpath, dirnames, _ in os.walk(cache_path):
        if "train" in dirnames and "valid" in dirnames and "test" in dirnames:
            return dirpath
    raise FileNotFoundError(
        f"Could not find train/valid/test folders under {cache_path}"
    )

# ── MAIN ──────────────────────────────────────────────────────────────────────

def main() -> None:
    _mount_drive()
    _make_dirs()

    print("\nDownloading dataset from Kaggle …")
    cache_path = kagglehub.dataset_download("xhlulu/140k-real-and-fake-faces")
    print(f"Kaggle cache path: {cache_path}")

    split_root = _find_split_root(cache_path)
    print(f"Split root found: {split_root}")

    total_saved = total_skipped = total_failed = 0

    for src_split, dst_split in SPLIT_MAP.items():
        for src_label, dst_label in LABEL_MAP.items():

            src_dir = os.path.join(split_root, src_split, src_label)
            dst_dir = os.path.join(DATASET_DIR, dst_split, dst_label)

            if not os.path.isdir(src_dir):
                print(f"\n  [warn] Source folder not found, skipping: {src_dir}")
                continue

            image_files = sorted(
                p for p in Path(src_dir).iterdir()
                if p.suffix.lower() in {".jpg", ".jpeg", ".png", ".webp"}
            )

            print(f"\n{'─'*60}")
            print(f"  {src_split}/{src_label}  →  {dst_split}/{dst_label}  ({len(image_files)} images)")
            print(f"{'─'*60}")

            saved = skipped = failed = 0

            for src_path in tqdm(image_files, desc=f"{dst_split}/{dst_label}", unit="img"):
                dst_path = os.path.join(dst_dir, src_path.stem + ".png")

                if os.path.exists(dst_path):
                    skipped += 1
                    continue

                try:
                    img       = Image.open(src_path)
                    processed = _preprocess(img)
                except (UnidentifiedImageError, Exception) as exc:
                    print(f"\n  [!] Cannot open {src_path.name}: {exc}")
                    failed += 1
                    continue

                if _save_with_retry(processed, dst_path):
                    saved += 1
                else:
                    print(f"\n  [!] Permanently failed to save {src_path.name}")
                    failed += 1

            print(f"  ✓  saved={saved}  skipped={skipped}  failed={failed}")
            total_saved   += saved
            total_skipped += skipped
            total_failed  += failed

    print(f"\n{'═'*60}")
    print(f"DONE  |  saved={total_saved}  skipped={total_skipped}  failed={total_failed}")
    print(f"Output: {DATASET_DIR}")
    print(f"{'═'*60}")


if __name__ == "__main__":
    main()